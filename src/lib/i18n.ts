export function translate(language: UILanguage, key: TranslationKey, vars?: Record<string, string | number>) {
  const source = translations[language][key] ?? en[key]

  if (!vars) {
    return source
  }

  return Object.entries(vars).reduce((message, [token, value]) => {
    return message.replaceAll(`{{${token}}}`, String(value))
  }, source)
}
